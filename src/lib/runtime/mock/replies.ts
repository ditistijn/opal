/** Scripted assistant turns for the mock runtime, chosen from the prompt text. */
import type { ModeID } from "../contracts"
import { INLINE_TOUR_STEPS } from "./inline-tour"

/** Mirrors OpenCode's `question` tool input (`Question.Prompt`). */
export interface MockQuestion {
  header: string
  question: string
  options: { label: string; description: string }[]
  multiple?: boolean
}

export type Step =
  | { kind: "reasoning"; text: string }
  /** `words`: whitespace-separated words streamed per tick (default 3); long code fences use more. */
  | { kind: "text"; text: string; words?: number }
  | {
      kind: "tool"
      name: string
      input: Record<string, unknown>
      output: string
      ticks: number
      artifact?: { title: string; files: Record<string, string>; entry: string }
    }
  | { kind: "permission"; action: string; resources: string[]; message: string }
  | { kind: "question"; questions: MockQuestion[] }
  | { kind: "error"; message: string }

function artifactHtml(title: string) {
  return `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>
<style>body{font-family:-apple-system,system-ui,sans-serif;margin:0;padding:32px;background:#fbfaf7;color:#1d1c1a}
h1{font-size:20px} .card{background:#fff;border:1px solid #e7e4da;border-radius:10px;padding:16px;margin-top:12px}</style>
</head><body><h1>${title}</h1><div class="card">Generated by the mock runtime.</div></body></html>`
}

export function scriptFor(text: string, mode: ModeID | undefined): Step[] {
  const t = text.toLowerCase()
  if (t.includes("fail") || t.includes("error")) {
    return [
      { kind: "text", text: "Let me try that…" },
      { kind: "error", message: "Provider returned 529: overloaded. Try again in a moment." },
    ]
  }
  if (t.includes("question")) {
    return [
      {
        kind: "reasoning",
        text: "A couple of choices here are a matter of taste, so I'll ask before writing anything.",
      },
      {
        kind: "question",
        questions: [
          {
            header: "Format",
            question: "Which format should the summary use?",
            options: [
              {
                label: "Bullet points (Recommended)",
                description: "Short, skimmable list of the key points",
              },
              { label: "Short essay", description: "Two or three connected paragraphs" },
              { label: "Table", description: "Side-by-side comparison of the options" },
            ],
          },
          {
            header: "Sections",
            question: "Which sections should it include?",
            multiple: true,
            options: [
              { label: "Background", description: "Context a newcomer needs" },
              { label: "Trade-offs", description: "What each option costs" },
              { label: "Next steps", description: "Concrete follow-ups" },
            ],
          },
        ],
      },
      { kind: "text", text: "I'll draft it that way and share it here when it's ready." },
    ]
  }
  if (t.includes("delete") || t.includes("permission") || t.includes("outside")) {
    return [
      {
        kind: "reasoning",
        text: "This needs to touch files outside the conversation folder, so I'll ask first.",
      },
      {
        kind: "permission",
        action: "edit",
        resources: ["~/Documents/notes/old-drafts/*"],
        message: "Opal wants to delete 14 files in ~/Documents/notes/old-drafts",
      },
      {
        kind: "tool",
        name: "bash",
        input: { command: "rm -r ~/Documents/notes/old-drafts" },
        output: "",
        ticks: 6,
      },
      { kind: "text", text: "Done — the old drafts folder has been removed." },
    ]
  }
  // Before the research and artifact branches: "inline chart" must not become an artifact.
  if (t.includes("inline")) return INLINE_TOUR_STEPS.map((step) => ({ ...step }))
  if (t.includes("search") || t.includes("research") || t.includes("latest") || mode === "research") {
    return [
      { kind: "reasoning", text: "I'll search for recent sources and then summarize what they agree on." },
      {
        kind: "tool",
        name: "websearch",
        input: { query: text.slice(0, 80) },
        output:
          "1. example.com/overview — An overview\n2. example.org/analysis — A deeper analysis\n3. example.net/news — Recent news",
        ticks: 10,
      },
      {
        kind: "text",
        text: `Here's what I found across **3 sources**:\n\n- The overview and the analysis agree on the main trend.\n- Recent news suggests the picture is still evolving.\n\nSources: [example.com](https://example.com), [example.org](https://example.org).`,
      },
    ]
  }
  if (/(dashboard|diagram|chart|artifact|app|page|game|draw|visual)/.test(t) || mode === "artifact") {
    const title =
      text.length > 48
        ? `${text.slice(0, 45).trim()}…`
        : text.replace(/^(make|build|create|draw)\s+(me\s+)?(a|an)\s+/i, "")
    const nice = title.charAt(0).toUpperCase() + title.slice(1)
    return [
      {
        kind: "reasoning",
        text: "A single self-contained HTML artifact will work best here. I'll lay out the structure, then write it.",
      },
      {
        kind: "tool",
        name: "artifact_create",
        input: { title: nice, entry: "index.html" },
        output: "Artifact created",
        ticks: 14,
        artifact: { title: nice, files: { "index.html": artifactHtml(nice) }, entry: "index.html" },
      },
      {
        kind: "text",
        text: `I've created **${nice}** — it's open in the panel on the right.\n\nIt's a single HTML file, so you can download it or ask me to change anything: layout, colors, data, or interactions.`,
      },
    ]
  }
  return [
    { kind: "reasoning", text: "Short, direct answer with an example." },
    {
      kind: "text",
      text: `Sure. Here's a concise answer.\n\n**Key idea:** break the problem into small, testable steps.\n\n1. Define the input and expected output.\n2. Write the simplest version that works.\n3. Refine.\n\n\`\`\`ts\nexport function solve(input: string): string {\n  return input.trim().split(/\\s+/).reverse().join(" ")\n}\n\`\`\`\n\nLet me know if you'd like me to go deeper on any step.`,
    },
  ]
}
