//! OS-level sandbox for agent shell commands (macOS `sandbox-exec`). Owner: runtime.
//!
//! At startup Opal installs `<root>/bin/sandbox/zsh`, a small POSIX sh wrapper that OpenCode uses as its
//! configured `shell` (opencode.json `shell: "<path>"`, resolved by core/src/shell/select.ts). It is named
//! `zsh` so OpenCode keeps zsh semantics: `-c <command>` for the shell tool, `-l` for PTY terminals and
//! the zsh dialect in the permission scanner. The wrapper:
//!
//!  1. reads `<root>/bin/sandbox/config.env` (`OPAL_SANDBOX_MODE=off|filesystem|strict`,
//!     `OPAL_SANDBOX_ALLOW=<colon-separated extra write roots>`), written by `cmd_sandbox_configure`;
//!  2. with mode `off` (or no `/usr/bin/sandbox-exec`) simply `exec /bin/zsh "$@"`;
//!  3. otherwise computes the writable roots — the command's working directory (OpenCode runs commands
//!     with cwd = the session directory), the enclosing git work tree and, for linked worktrees, the
//!     repository's common `.git` dir, `$TMPDIR`, `/private/tmp`, `/private/var/folders`, `/dev`, package
//!     manager caches (filesystem mode) and the user's extra folders — and builds an SBPL profile:
//!     `(allow default) (deny file-write*) (allow file-write* (subpath …) …)`, re-denying Opal's own
//!     wrapper/config and `.git/hooks` of a linked worktree's main repository; strict mode adds
//!     `(deny network-outbound) (allow network-outbound (remote ip "localhost:*"))`;
//!  4. `exec /usr/bin/sandbox-exec -p "$profile" /bin/zsh "$@"`.
//!
//! See docs/SECURITY.md for what this does and does not protect.
use crate::paths::OpalPaths;
use serde::Serialize;
use std::path::{Path, PathBuf};

pub const SANDBOX_EXEC: &str = "/usr/bin/sandbox-exec";
const MODES: &[&str] = &["off", "filesystem", "strict"];
const DEFAULT_MODE: &str = "filesystem";

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SandboxStatus {
    /// `/usr/bin/sandbox-exec` exists (macOS) and the wrapper is installed.
    pub available: bool,
    pub mode: String,
    pub allow: Vec<String>,
    /// Absolute path of the wrapper shell, for opencode.json `shell`.
    pub shell_path: String,
}

pub fn sandbox_dir(paths: &OpalPaths) -> PathBuf {
    paths.root.join("bin").join("sandbox")
}

pub fn shell_path(paths: &OpalPaths) -> PathBuf {
    sandbox_dir(paths).join("zsh")
}

fn config_file(paths: &OpalPaths) -> PathBuf {
    sandbox_dir(paths).join("config.env")
}

/// Single-quotes a value for POSIX sh.
fn sh_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

/// The wrapper script for an Opal root. `sandbox_dir` and `opal_root` are embedded (sh-quoted).
pub fn wrapper_script(sandbox_dir: &Path, opal_root: &Path) -> String {
    let header = format!(
        "#!/bin/sh\n\
         # Opal sandbox shell — generated by Opal (src-tauri/src/sandbox_exec.rs); rewritten on every launch.\n\
         SANDBOX_DIR={}\n\
         OPAL_ROOT={}\n",
        sh_quote(&sandbox_dir.to_string_lossy()),
        sh_quote(&opal_root.to_string_lossy()),
    );
    format!("{header}{WRAPPER_BODY}")
}

/// The wrapper body (POSIX sh). Expects `SANDBOX_DIR` and `OPAL_ROOT` to be set by the header.
const WRAPPER_BODY: &str = include_str!("sandbox_shell.sh");

/// Writes a file via temp + rename (never a partially written script/config).
fn write_atomic(path: &Path, contents: &str, mode: u32) -> anyhow::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let tmp = path.with_extension(format!("tmp-{}", uuid::Uuid::new_v4().simple()));
    std::fs::write(&tmp, contents)?;
    std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode))?;
    std::fs::rename(&tmp, path).inspect_err(|_| {
        let _ = std::fs::remove_file(&tmp);
    })?;
    Ok(())
}

/// Installs (or refreshes) the wrapper; creates a default config.env when none exists yet.
pub fn install(paths: &OpalPaths) -> anyhow::Result<PathBuf> {
    let dir = sandbox_dir(paths);
    let script = wrapper_script(&dir, &paths.root);
    let target = shell_path(paths);
    if std::fs::read_to_string(&target).ok().as_deref() != Some(script.as_str()) {
        write_atomic(&target, &script, 0o755)?;
    }
    if !config_file(paths).exists() {
        write_atomic(&config_file(paths), &config_env(DEFAULT_MODE, &[], &[]), 0o644)?;
    }
    Ok(target)
}

pub fn setup() {
    match OpalPaths::resolve().and_then(|paths| install(&paths)) {
        Ok(path) => log::info!("sandbox shell installed at {}", path.display()),
        Err(e) => log::warn!("could not install the sandbox shell: {e}"),
    }
}

fn config_env(mode: &str, allow: &[String], deny_ports: &[u16]) -> String {
    format!(
        "# Written by Opal (Settings → Security). Read by ./zsh on every command.\n\
         OPAL_SANDBOX_MODE={mode}\n\
         OPAL_SANDBOX_ALLOW={}\n\
         OPAL_SANDBOX_DENY_PORTS={}\n",
        allow.join(":"),
        deny_ports
            .iter()
            .map(u16::to_string)
            .collect::<Vec<_>>()
            .join(":")
    )
}

struct SandboxConfig {
    mode: String,
    allow: Vec<String>,
    /// Loopback ports commands may never connect to (the engine and the remote-control web server).
    deny_ports: Vec<u16>,
}

fn read_config(paths: &OpalPaths) -> SandboxConfig {
    let mut cfg = SandboxConfig {
        mode: DEFAULT_MODE.to_string(),
        allow: Vec::new(),
        deny_ports: Vec::new(),
    };
    if let Ok(text) = std::fs::read_to_string(config_file(paths)) {
        for line in text.lines() {
            if let Some(v) = line.strip_prefix("OPAL_SANDBOX_MODE=") {
                cfg.mode = v.trim().to_string();
            } else if let Some(v) = line.strip_prefix("OPAL_SANDBOX_ALLOW=") {
                cfg.allow = v
                    .split(':')
                    .filter(|p| !p.is_empty())
                    .map(str::to_string)
                    .collect();
            } else if let Some(v) = line.strip_prefix("OPAL_SANDBOX_DENY_PORTS=") {
                cfg.deny_ports = v.split(':').filter_map(|p| p.trim().parse().ok()).collect();
            }
        }
    }
    cfg
}

/// Records the loopback ports commands must not reach (called by the sidecar once it knows its port).
pub fn publish_deny_ports(ports: &[u16]) {
    let Ok(paths) = OpalPaths::resolve() else { return };
    if let Err(e) = install(&paths) {
        log::warn!("sandbox: could not install the wrapper: {e}");
        return;
    }
    let cfg = read_config(&paths);
    let mut deny: Vec<u16> = ports.to_vec();
    deny.sort_unstable();
    deny.dedup();
    if cfg.deny_ports == deny {
        return;
    }
    if let Err(e) = write_atomic(
        &config_file(&paths),
        &config_env(&cfg.mode, &cfg.allow, &deny),
        0o644,
    ) {
        log::warn!("sandbox: could not record denied ports: {e}");
    }
}

/// Extra write roots must be absolute, single-line and colon-free (config.env is colon-separated).
fn validate_allow(allow: &[String]) -> Result<Vec<String>, String> {
    let mut out: Vec<String> = Vec::new();
    for raw in allow {
        let p = raw.trim().trim_end_matches('/');
        let p = if p.is_empty() && raw.trim().starts_with('/') {
            "/"
        } else {
            p
        };
        if p.is_empty() {
            continue;
        }
        if !p.starts_with('/') {
            return Err(format!("not an absolute path: {raw}"));
        }
        if p.contains(':') || p.contains('\n') || p.contains('\r') || p.contains('\0') {
            return Err(format!("unsupported character in path: {raw}"));
        }
        if !out.iter().any(|q| q == p) {
            out.push(p.to_string());
        }
    }
    Ok(out)
}

#[tauri::command]
pub async fn cmd_sandbox_status() -> Result<SandboxStatus, String> {
    let paths = OpalPaths::resolve().map_err(|e| e.to_string())?;
    let shell = install(&paths).map_err(|e| e.to_string())?;
    let cfg = read_config(&paths);
    Ok(SandboxStatus {
        available: Path::new(SANDBOX_EXEC).exists(),
        mode: cfg.mode,
        allow: cfg.allow,
        shell_path: shell.to_string_lossy().into_owned(),
    })
}

#[tauri::command]
pub async fn cmd_sandbox_configure(
    mode: String,
    allow: Vec<String>,
) -> Result<SandboxStatus, String> {
    if !MODES.contains(&mode.as_str()) {
        return Err(format!("unknown sandbox mode: {mode}"));
    }
    let allow = validate_allow(&allow)?;
    let paths = OpalPaths::resolve().map_err(|e| e.to_string())?;
    install(&paths).map_err(|e| e.to_string())?;
    let deny_ports = read_config(&paths).deny_ports;
    write_atomic(&config_file(&paths), &config_env(&mode, &allow, &deny_ports), 0o644)
        .map_err(|e| e.to_string())?;
    cmd_sandbox_status().await
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_root() -> PathBuf {
        let dir = std::env::temp_dir().join(format!("opal-sbx-{}", uuid::Uuid::new_v4().simple()));
        std::fs::create_dir_all(&dir).unwrap();
        dir.canonicalize().unwrap()
    }

    fn print_profile(
        root: &Path,
        cwd: &Path,
        mode: &str,
        allow: &[String],
        args: &[&str],
    ) -> String {
        let dir = root.join("bin").join("sandbox");
        write_atomic(&dir.join("zsh"), &wrapper_script(&dir, root), 0o755).unwrap();
        write_atomic(&dir.join("config.env"), &config_env(mode, allow, &[]), 0o644).unwrap();
        let out = std::process::Command::new(dir.join("zsh"))
            .args(args)
            .current_dir(cwd)
            .env("OPAL_SANDBOX_PRINT_PROFILE", "1")
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        String::from_utf8(out.stdout).unwrap()
    }

    #[test]
    fn sh_quote_escapes_single_quotes() {
        assert_eq!(sh_quote("a'b"), r"'a'\''b'");
    }

    #[test]
    fn profile_quotes_paths_and_dedupes_roots() {
        let root = temp_root();
        let work = root.join("conv \"quoted\" back\\slash");
        std::fs::create_dir_all(&work).unwrap();
        let extra = root.join("extra");
        std::fs::create_dir_all(&extra).unwrap();
        let extra_s = extra.to_string_lossy().into_owned();
        let profile = print_profile(
            &root,
            &work,
            "filesystem",
            &[
                extra_s.clone(),
                extra_s.clone(),
                work.to_string_lossy().into_owned(),
            ],
            &["-c", "true"],
        );
        let escaped = work
            .to_string_lossy()
            .replace('\\', r"\\")
            .replace('"', "\\\"");
        assert!(profile.starts_with("(version 1)\n(allow default)\n(deny file-write*)"));
        // Each root is listed once in the write-allow block and once in the read-allow block (after the secret denies).
        assert_eq!(
            profile.matches(&format!("(subpath \"{escaped}\")")).count(),
            2,
            "{profile}"
        );
        assert_eq!(
            profile.matches(&format!("(subpath \"{extra_s}\")")).count(),
            2,
            "{profile}"
        );
        assert!(profile.contains("(deny file-read*"), "{profile}");
        assert!(
            profile.contains(&format!("(subpath \"{}/opencode/data\")", root.to_string_lossy())),
            "{profile}"
        );
        // Temp folders are write roots only; they are never re-allowed for reading.
        assert_eq!(
            profile.matches("(subpath \"/private/tmp\")").count(),
            1,
            "{profile}"
        );
        assert!(profile.contains("(literal \"/dev/null\")"));
        assert!(profile.contains(&format!(
            "(deny file-write*\n  (subpath \"{}/bin/sandbox\")",
            root.display()
        )));
        assert!(!profile.contains("network-outbound"));
        assert!(
            !profile.contains(".zsh_history"),
            "non-interactive shells get no history access"
        );
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn strict_mode_blocks_network_and_interactive_keeps_history() {
        let root = temp_root();
        let profile = print_profile(&root, &root, "strict", &[], &["-l"]);
        assert!(profile.ends_with(
            "(deny network-outbound)\n(allow network-outbound (remote ip \"localhost:*\"))\n"
        ));
        assert!(profile.contains(".zsh_history"));
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn home_is_never_a_root() {
        let root = temp_root();
        let home = dirs::home_dir().unwrap().canonicalize().unwrap();
        let profile = print_profile(&root, &home, "filesystem", &[], &["-c", "true"]);
        assert!(
            !profile.contains(&format!("(subpath \"{}\")", home.display())),
            "{profile}"
        );
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn validates_allow_paths() {
        assert_eq!(
            validate_allow(&["/a/".into(), "/a".into(), " ".into()]).unwrap(),
            vec!["/a".to_string()]
        );
        assert!(validate_allow(&["rel".into()]).is_err());
        assert!(validate_allow(&["/a:b".into()]).is_err());
    }
}
